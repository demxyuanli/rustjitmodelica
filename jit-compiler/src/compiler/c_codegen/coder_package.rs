//! Coder-grade deployment package around residual/jacobian C emit.
//! Provides a fixed-step host/embedded API (init/step/terminate), CMake, and interface manifest.
//! This is not MathWorks Embedded Coder; it is the rustmodlica deployment packaging tier.

use serde::Serialize;
use std::io::Write;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CoderInterfaceManifest {
    pub generator: String,
    pub model_name: String,
    pub sample_time: f64,
    pub stop_time: f64,
    pub nx: usize,
    pub np: usize,
    pub ny: usize,
    pub has_jacobian: bool,
    pub states: Vec<String>,
    pub parameters: Vec<String>,
    pub outputs: Vec<String>,
    pub api: Vec<&'static str>,
}

#[derive(Debug, Clone)]
pub struct CoderPackageInfo {
    pub model_name: String,
    pub state_vars: Vec<String>,
    pub param_vars: Vec<String>,
    pub output_vars: Vec<String>,
    pub sample_time: f64,
    pub stop_time: f64,
    pub has_jacobian: bool,
}

/// Write deployment files next to model.c / model.h.
pub fn write_coder_package(dir: &Path, info: &CoderPackageInfo) -> Result<Vec<PathBuf>, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let mut written = Vec::new();

    written.push(write_text(dir, "rml_step.h", RML_STEP_H)?);
    written.push(write_text(
        dir,
        "rml_step.c",
        &render_rml_step_c(info),
    )?);
    written.push(write_text(
        dir,
        "rml_main.c",
        &render_rml_main_c(info),
    )?);
    written.push(write_text(
        dir,
        "CMakeLists.txt",
        &render_cmake(info),
    )?);
    written.push(write_text(
        dir,
        "INTEGRATION.txt",
        &render_integration_txt(info),
    )?);

    let manifest = CoderInterfaceManifest {
        generator: "rustmodlica-coder-package".into(),
        model_name: info.model_name.clone(),
        sample_time: info.sample_time,
        stop_time: info.stop_time,
        nx: info.state_vars.len(),
        np: info.param_vars.len(),
        ny: info.output_vars.len(),
        has_jacobian: info.has_jacobian,
        states: info.state_vars.clone(),
        parameters: info.param_vars.clone(),
        outputs: info.output_vars.clone(),
        api: vec![
            "rml_model_create",
            "rml_model_destroy",
            "rml_model_set_param",
            "rml_model_get_output",
            "rml_model_step",
            "rml_model_time",
        ],
    };
    let json = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())?;
    written.push(write_text(dir, "interface.json", &json)?);

    Ok(written)
}

fn write_text(dir: &Path, name: &str, body: &str) -> Result<PathBuf, String> {
    let path = dir.join(name);
    let mut f = std::fs::File::create(&path).map_err(|e| e.to_string())?;
    f.write_all(body.as_bytes()).map_err(|e| e.to_string())?;
    Ok(path)
}

const RML_STEP_H: &str = r#"/* Generated by rustmodlica coder package. Not MathWorks Embedded Coder. */
#ifndef RML_STEP_H
#define RML_STEP_H

#include <stddef.h>

#ifdef __cplusplus
extern "C" {
#endif

typedef struct rml_model rml_model_t;

rml_model_t* rml_model_create(void);
void rml_model_destroy(rml_model_t* m);

size_t rml_model_nx(const rml_model_t* m);
size_t rml_model_np(const rml_model_t* m);
size_t rml_model_ny(const rml_model_t* m);

int rml_model_set_param(rml_model_t* m, size_t index, double value);
int rml_model_get_param(const rml_model_t* m, size_t index, double* out);
int rml_model_get_state(const rml_model_t* m, size_t index, double* out);
int rml_model_set_state(rml_model_t* m, size_t index, double value);
int rml_model_get_output(const rml_model_t* m, size_t index, double* out);

double rml_model_sample_time(const rml_model_t* m);
double rml_model_time(const rml_model_t* m);

/* Fixed-step RK4 using residual(). Returns 0 on success. */
int rml_model_step(rml_model_t* m);

#ifdef __cplusplus
}
#endif

#endif /* RML_STEP_H */
"#;

fn render_rml_step_c(info: &CoderPackageInfo) -> String {
    let nx = info.state_vars.len();
    let np = info.param_vars.len();
    let ny = info.output_vars.len();
    let nx_buf = nx.max(1);
    let np_buf = np.max(1);
    let ny_buf = ny.max(1);
    let dt = if info.sample_time.is_finite() && info.sample_time > 0.0 {
        info.sample_time
    } else {
        0.001
    };
    format!(
        r#"/* Generated by rustmodlica coder package. Fixed-step host/embedded wrapper. */
#include "rml_step.h"
#include "model.h"
#include <stdlib.h>
#include <string.h>

struct rml_model {{
  double t;
  double dt;
  double x[{nx_buf}];
  double p[{np_buf}];
  double y[{ny_buf}];
  double xdot[{nx_buf}];
  double k1[{nx_buf}];
  double k2[{nx_buf}];
  double k3[{nx_buf}];
  double k4[{nx_buf}];
  double xt[{nx_buf}];
}};

rml_model_t* rml_model_create(void) {{
  rml_model_t* m = (rml_model_t*)calloc(1, sizeof(rml_model_t));
  if (!m) return NULL;
  m->t = 0.0;
  m->dt = {dt:.17e};
  residual(m->t, m->x, m->xdot, m->p, m->y);
  return m;
}}

void rml_model_destroy(rml_model_t* m) {{
  free(m);
}}

size_t rml_model_nx(const rml_model_t* m) {{ (void)m; return {nx}; }}
size_t rml_model_np(const rml_model_t* m) {{ (void)m; return {np}; }}
size_t rml_model_ny(const rml_model_t* m) {{ (void)m; return {ny}; }}

int rml_model_set_param(rml_model_t* m, size_t index, double value) {{
  if (!m || index >= {np}) return -1;
  m->p[index] = value;
  return 0;
}}

int rml_model_get_param(const rml_model_t* m, size_t index, double* out) {{
  if (!m || !out || index >= {np}) return -1;
  *out = m->p[index];
  return 0;
}}

int rml_model_get_state(const rml_model_t* m, size_t index, double* out) {{
  if (!m || !out || index >= {nx}) return -1;
  *out = m->x[index];
  return 0;
}}

int rml_model_set_state(rml_model_t* m, size_t index, double value) {{
  if (!m || index >= {nx}) return -1;
  m->x[index] = value;
  return 0;
}}

int rml_model_get_output(const rml_model_t* m, size_t index, double* out) {{
  if (!m || !out || index >= {ny}) return -1;
  *out = m->y[index];
  return 0;
}}

double rml_model_sample_time(const rml_model_t* m) {{
  return m ? m->dt : 0.0;
}}

double rml_model_time(const rml_model_t* m) {{
  return m ? m->t : 0.0;
}}

int rml_model_step(rml_model_t* m) {{
  size_t i;
  double h;
  if (!m) return -1;
  h = m->dt;
#if {nx} == 0
  residual(m->t, m->x, m->xdot, m->p, m->y);
  m->t += h;
  return 0;
#else
  residual(m->t, m->x, m->k1, m->p, m->y);
  for (i = 0; i < {nx}; ++i) m->xt[i] = m->x[i] + 0.5 * h * m->k1[i];
  residual(m->t + 0.5 * h, m->xt, m->k2, m->p, m->y);
  for (i = 0; i < {nx}; ++i) m->xt[i] = m->x[i] + 0.5 * h * m->k2[i];
  residual(m->t + 0.5 * h, m->xt, m->k3, m->p, m->y);
  for (i = 0; i < {nx}; ++i) m->xt[i] = m->x[i] + h * m->k3[i];
  residual(m->t + h, m->xt, m->k4, m->p, m->y);
  for (i = 0; i < {nx}; ++i) {{
    m->x[i] += (h / 6.0) * (m->k1[i] + 2.0 * m->k2[i] + 2.0 * m->k3[i] + m->k4[i]);
  }}
  residual(m->t + h, m->x, m->xdot, m->p, m->y);
  m->t += h;
  return 0;
#endif
}}
"#,
        nx = nx,
        np = np,
        ny = ny,
        nx_buf = nx_buf,
        np_buf = np_buf,
        ny_buf = ny_buf,
        dt = dt,
    )
}

fn render_rml_main_c(info: &CoderPackageInfo) -> String {
    let steps = if info.sample_time > 0.0 && info.stop_time > 0.0 {
        ((info.stop_time / info.sample_time).ceil() as usize).max(1)
    } else {
        1000
    };
    let print_y = if info.output_vars.is_empty() {
        "    (void)y0;\n".to_string()
    } else {
        "    printf(\"t=%.6f y0=%.6f\\n\", rml_model_time(m), y0);\n".to_string()
    };
    format!(
        r#"/* Host demo for rustmodlica coder package. */
#include "rml_step.h"
#include <stdio.h>

int main(void) {{
  size_t i;
  double y0 = 0.0;
  rml_model_t* m = rml_model_create();
  if (!m) {{
    fprintf(stderr, "rml_model_create failed\\n");
    return 1;
  }}
  printf("model={model} nx=%zu np=%zu ny=%zu dt=%.6g\\n",
         rml_model_nx(m), rml_model_np(m), rml_model_ny(m), rml_model_sample_time(m));
  for (i = 0; i < {steps}u; ++i) {{
    if (rml_model_step(m) != 0) {{
      fprintf(stderr, "step failed\\n");
      rml_model_destroy(m);
      return 2;
    }}
    if (rml_model_ny(m) > 0) {{
      rml_model_get_output(m, 0, &y0);
    }}
{print_y}  }}
  rml_model_destroy(m);
  return 0;
}}
"#,
        model = info.model_name,
        steps = steps,
        print_y = print_y,
    )
}

fn render_cmake(info: &CoderPackageInfo) -> String {
    let jac_note = if info.has_jacobian {
        "# jacobian() is available in model.c"
    } else {
        "# no symbolic jacobian emitted"
    };
    format!(
        r#"# Generated by rustmodlica coder package for {model}
cmake_minimum_required(VERSION 3.16)
project({safe} C)
set(CMAKE_C_STANDARD 99)
{jac_note}
add_library(rml_model STATIC model.c rml_step.c)
target_include_directories(rml_model PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}})
if(NOT WIN32)
  target_link_libraries(rml_model PUBLIC m)
endif()

add_executable(rml_host rml_main.c)
target_link_libraries(rml_host PRIVATE rml_model)
"#,
        model = info.model_name,
        safe = sanitize_c_ident(&info.model_name),
        jac_note = jac_note,
    )
}

